def anime_recommendations(anime_name, similarity_data, anime_data, k=10):
    """
    Menghasilkan rekomendasi anime berbasis konten (item-ke-item) yang detail.
    Fungsi ini bisa digunakan untuk menampilkan rekomendasi langsung atau untuk evaluasi.

    Args:
        anime_name (str): Nama anime yang ingin dicari rekomendasinya.
        similarity_data (pd.DataFrame): DataFrame matriks kemiripan Cosine.
        anime_data (pd.DataFrame): DataFrame data anime yang sudah diproses
                                    (harus memiliki kolom 'name' dan detail lainnya).
        k (int): Jumlah rekomendasi yang diinginkan.

    Returns:
        pd.DataFrame: DataFrame berisi rekomendasi anime beserta detail dan skor kemiripan.
                      Mengembalikan None jika anime tidak ditemukan atau error lain.
    """
    if not isinstance(similarity_data, pd.DataFrame) or similarity_data.empty:
        print("Data kemiripan (similarity_data) tidak valid atau kosong.")
        return None
    if not isinstance(anime_data, pd.DataFrame) or anime_data.empty:
        print("Data anime (anime_data) tidak valid atau kosong.")
        return None
    if 'name' not in anime_data.columns:
        print("Kolom 'name' tidak ditemukan di anime_data.")
        return None

    # Cek apakah anime_name ada dalam index similarity_data
    if anime_name not in similarity_data.index:
        print(f"Anime '{anime_name}' tidak ditemukan dalam data kemiripan.")
        return None

    # Ambil skor kemiripan untuk anime yang diberikan
    similarity_scores_series = similarity_data.loc[anime_name]

    # Urutkan anime berdasarkan skor kemiripan (descending)
    sorted_series = similarity_scores_series.sort_values(ascending=False)

    # Ambil k+1 teratas dan buang yang pertama (anime itu sendiri)
    # Pastikan ada cukup item setelah membuang diri sendiri
    if len(sorted_series) > 1:
        top_k_others_indices = sorted_series.index[1:k+1]
        top_k_others_scores = sorted_series.values[1:k+1]
    else: # Kasus langka dimana hanya ada anime itu sendiri atau tidak ada yang lain
        return pd.DataFrame() # Kembalikan DataFrame kosong

    if len(top_k_others_indices) == 0: # Jika setelah slicing tidak ada item (misal k=0 atau tidak ada item lain)
        return pd.DataFrame()

    # Ambil detail anime dari dataframe anime_data berdasarkan nama anime
    try:
        # Jika 'name' belum menjadi index di anime_data, set dulu
        if anime_data.index.name != 'name':
            anime_data_indexed = anime_data.set_index('name')
        else:
            anime_data_indexed = anime_data

        # Filter hanya nama yang ada di anime_data_indexed untuk menghindari KeyError
        valid_indices = [idx for idx in top_k_others_indices if idx in anime_data_indexed.index]
        if not valid_indices:
            print("Tidak ada anime rekomendasi yang ditemukan di anime_data.")
            return pd.DataFrame()

        recommended_anime_details = anime_data_indexed.loc[valid_indices].copy()

        # Karena 'scores' mungkin tidak lagi selaras jika ada valid_indices filtering,
        # kita ambil skor dari sorted_series berdasarkan valid_indices
        aligned_scores = sorted_series.loc[valid_indices].values
        recommended_anime_details['similarity_score'] = aligned_scores

    except KeyError as e:
        print(f"Error saat mengambil detail anime: {e}. Pastikan semua nama anime rekomendasi ada di 'anime_data'.")
        return None

    # Pilih kolom yang relevan untuk ditampilkan
    columns_to_select = ['genre', 'type', 'rating', 'members', 'episodes', 'similarity_score']
    existing_columns = [col for col in columns_to_select if col in recommended_anime_details.columns or col == 'similarity_score']

    recommended_anime_final = recommended_anime_details[existing_columns]

    recommended_anime_final = recommended_anime_final.rename(columns={
        'genre': 'Genre',
        'type': 'Type',
        'rating': 'Rating (Source)',
        'members': 'Members',
        'episodes': 'Episodes',
        'similarity_score': 'Similarity Score'
    })

    # Urutkan sekali lagi berdasarkan similarity score karena .loc mungkin tidak menjaga urutan dari valid_indices
    if 'Similarity Score' in recommended_anime_final.columns:
        recommended_anime_final = recommended_anime_final.sort_values('Similarity Score', ascending=False)

    return recommended_anime_final.head(k) # Pastikan mengembalikan k item

