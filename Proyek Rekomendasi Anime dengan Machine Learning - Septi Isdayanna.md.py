# Fungsi evaluasi

def content_based_evaluation(anime_data, similarity_data, user_ratings_input, k=10, threshold=7):
    """
    Mengevaluasi sistem rekomendasi berbasis konten.
    """
    # Pastikan anime_data memiliki kolom 'name' dan 'anime_id'
    if not all(col in anime_data.columns for col in ['name', 'anime_id']):
        print("anime_data harus memiliki kolom 'name' dan 'anime_id'.")
        return {"Error": "Format anime_data tidak sesuai."}

    name_to_id = anime_data.set_index('name')['anime_id'].to_dict()
    id_to_name = {v: k for k, v in name_to_id.items()}

    available_anime_ids = set(anime_data['anime_id'])
    user_ratings_eval = user_ratings_input[user_ratings_input['anime_id'].isin(available_anime_ids)]
    positive_ratings = user_ratings_eval[user_ratings_eval['rating'] >= threshold]
    user_positive_items = positive_ratings.groupby('user_id')['anime_id'].apply(list)

    precision_list = []
    recall_list = []
    users_processed_for_eval = 0

    for user_id, positive_items_ids in user_positive_items.items():
        if not positive_items_ids or len(positive_items_ids) < 2: # Butuh minimal 2 untuk seed dan test
            continue

        users_processed_for_eval +=1

        # Pilih seed dan item tes
        # Membuat salinan untuk di-shuffle agar tidak mengubah list asli
        current_positive_ids = list(positive_items_ids)
        np.random.shuffle(current_positive_ids)

        seed_anime_id = current_positive_ids[0]
        relevant_items_ids = set(current_positive_ids[1:]) # Item relevan adalah sisanya

        seed_anime_name = id_to_name.get(seed_anime_id)

        if seed_anime_name is None or seed_anime_name not in similarity_data.index:
            continue

        # Panggil fungsi rekomendasi yang sudah didefinisikan diatas
        recommendations_df = anime_recommendations( # Menggunakan fungsi yang sama
            seed_anime_name,
            similarity_data=similarity_data,
            anime_data=anime_data, # anime_data di sini adalah anime_cleaned
            k=k
        )

        if recommendations_df is None or recommendations_df.empty:
            # Jika tidak ada rekomendasi, presisi dan recall adalah 0 untuk pengguna ini jika ada item relevan
            if relevant_items_ids: # Hanya hitung jika ada sesuatu yang diharapkan
                 precision_list.append(0)
                 recall_list.append(0)
            continue

        # Pastikan kolom 'name' ada di recommendations_df
        if 'name' not in recommendations_df.columns:
             # Jika fungsi anime_recommendations mengembalikan nama sebagai index, reset dulu
            if recommendations_df.index.name == 'name' or isinstance(recommendations_df.index, pd.MultiIndex) == False : #cek jika index adalah nama
                 recommendations_df_temp = recommendations_df.reset_index()
                 if 'name' not in recommendations_df_temp.columns and 'index' in recommendations_df_temp.columns: # jika hasil reset_index kolomnya 'index'
                      recommendations_df_temp = recommendations_df_temp.rename(columns={'index':'name'})

                 if 'name' in recommendations_df_temp.columns:
                      recommended_anime_names = recommendations_df_temp['name'].tolist()
                 else: # fallback jika nama tetap tidak ditemukan
                      print(f"Peringatan: Kolom 'name' tidak ditemukan di output recommendations_df untuk seed {seed_anime_name}. Melewati user {user_id}.")
                      continue
            else:
                 print(f"Peringatan: Kolom 'name' tidak ditemukan di output recommendations_df untuk seed {seed_anime_name}. Melewati user {user_id}.")
                 continue
        else:
            recommended_anime_names = recommendations_df['name'].tolist()


        recommended_anime_ids = [name_to_id.get(name) for name in recommended_anime_names if name in name_to_id and name_to_id.get(name) is not None]

        true_positives = len(set(recommended_anime_ids) & relevant_items_ids)

        precision_at_k = true_positives / k if k > 0 else 0
        recall_at_k = true_positives / len(relevant_items_ids) if len(relevant_items_ids) > 0 else 0

        precision_list.append(precision_at_k)
        recall_list.append(recall_at_k)

    mean_precision = np.mean(precision_list) if precision_list else 0
    mean_recall = np.mean(recall_list) if recall_list else 0

    print(f"Jumlah pengguna yang diproses untuk evaluasi: {users_processed_for_eval}")

    return {
        f"Mean Precision@{k} (CBF)": mean_precision,
        f"Mean Recall@{k} (CBF)": mean_recall
    }

